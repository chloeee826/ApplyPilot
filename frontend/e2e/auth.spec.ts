import { expect, test } from '@playwright/test'

test('register → persistent session → sign out → second account has an empty workspace', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  expect((await page.request.get('/api/jobs')).status()).toBe(401)
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Email', { exact: true }).fill('browser-alice@example.test')
  await page.getByLabel('Password', { exact: true }).fill('synthetic-alice-password-42')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'How does your resume fit this job?' })).toBeVisible()
  const profile = await page.request.post('/api/profiles', { headers: { 'X-ApplyPilot-Request': '1' }, data: {
    full_name: 'Alice Private Resume', summary: 'Personal evidence', skills: ['Python'],
  } })
  expect(profile.status()).toBe(201)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Alice Private Resume', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  expect((await page.request.get('/api/profiles')).status()).toBe(401)
  await page.getByRole('button', { name: 'New here? Create an account' }).click()
  await page.getByLabel('Email', { exact: true }).fill('browser-bob@example.test')
  await page.getByLabel('Password', { exact: true }).fill('synthetic-bob-password-42')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Start with your resume', exact: true })).toBeVisible()
  await expect(page.getByText('Alice Private Resume', { exact: true })).toHaveCount(0)
  expect(await (await page.request.get('/api/profiles')).json()).toEqual([])
  expect((await page.request.get(`/api/profiles/${(await profile.json()).id}`)).status()).toBe(404)
  await page.reload()
  await expect(page.getByText('Signed in as browser-bob@example.test')).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/auth-mobile.png', fullPage: true })
})
